"""Agent 21 - QA Testing.

Converts requirements / bug reports into structured test cases and generates
pytest-style unit, integration and API test skeletons. Execution is only
*proposed* against environments listed in the authorised test-environment
registry; production targets are refused outright, and destructive test
plans are flagged and require explicit authorisation.
"""

from __future__ import annotations

import re
from typing import Any, Literal

from pydantic import BaseModel, Field

from app.agents.base import (
    AgentContext,
    AgentInput,
    AgentResult,
    AgentSpec,
    ApprovalRule,
    BaseAgent,
    ProposedAction,
)
from app.agents.common import guard_untrusted, sentences, stable_id
from app.agents.registry import register
from app.agents.services import AgentServices

DESTRUCTIVE = ["delete", "drop", "truncate", "wipe", "purge", "reset database", "rm -rf", "destroy", "load test", "stress test", "ddos"]
PROD_WORDS = ["prod", "production", "live", "customer-facing"]


class QAIn(AgentInput):
    title: str = Field(max_length=200)
    requirements: str = Field(min_length=10, max_length=50_000)
    kind: Literal["requirement", "bug_report"] = "requirement"
    target_environment: str | None = None
    api_base_path: str | None = None
    language: Literal["python"] = "python"
    request_execution: bool = False


class TestCase(BaseModel):
    id: str
    title: str
    level: Literal["unit", "integration", "api", "e2e"]
    preconditions: list[str] = Field(default_factory=list)
    steps: list[str]
    expected: str
    requirement_ref: str
    priority: Literal["P0", "P1", "P2", "P3"] = "P2"
    destructive: bool = False


class CaseSet(BaseModel):
    cases: list[TestCase] = Field(default_factory=list)


class QAOut(BaseModel):
    title: str
    test_cases: list[TestCase]
    generated_code: dict[str, str]
    environment: dict[str, Any]
    execution: dict[str, Any]
    destructive_cases: int
    coverage_notes: list[str]


def heuristic_cases(payload: QAIn, reqs: list[str]) -> CaseSet:
    cases: list[TestCase] = []
    for i, r in enumerate(reqs, start=1):
        ref = f"requirement:{i}"
        destructive = any(d in r.lower() for d in DESTRUCTIVE)
        base_id = stable_id("TC", payload.title, i)
        if payload.kind == "bug_report":
            cases.append(TestCase(id=f"{base_id}-R", title=f"Regression: {r[:80]}", level="integration", preconditions=["Test environment seeded with fixture data"], steps=["Reproduce the reported scenario", "Observe behaviour"], expected="Bug no longer reproduces; behaviour matches specification", requirement_ref=ref, priority="P1", destructive=destructive))
            continue
        cases.append(TestCase(id=f"{base_id}-H", title=f"Happy path: {r[:80]}", level="unit", steps=["Arrange valid inputs", "Act", "Assert expected outcome"], expected=r[:200], requirement_ref=ref, priority="P1", destructive=destructive))
        cases.append(TestCase(id=f"{base_id}-N", title=f"Negative: invalid input for '{r[:60]}'", level="unit", steps=["Arrange invalid/missing inputs", "Act", "Assert validation error"], expected="Request rejected with a clear validation error; no side effects", requirement_ref=ref, priority="P2"))
        if payload.api_base_path or re.search(r"\b(api|endpoint|request|response|http)\b", r, re.I):
            cases.append(TestCase(id=f"{base_id}-A", title=f"API contract: {r[:70]}", level="api", preconditions=["Authenticated test client"], steps=[f"Call {payload.api_base_path or '<endpoint>'}", "Validate status code and schema"], expected="200/201 with documented schema; 401 without auth", requirement_ref=ref, priority="P1"))
    return CaseSet(cases=cases)


def render_pytest(payload: QAIn, cases: list[TestCase]) -> dict[str, str]:
    mod = re.sub(r"[^a-z0-9]+", "_", payload.title.lower()).strip("_")[:40] or "feature"
    files: dict[str, str] = {}
    by_level: dict[str, list[TestCase]] = {}
    for c in cases:
        by_level.setdefault(c.level, []).append(c)
    for level, cs in by_level.items():
        lines = ['"""Auto-generated by OpsPilot QA Testing Agent. Review before use."""', "", "import pytest", ""]
        if level == "api":
            lines += ["from fastapi.testclient import TestClient", "", "", "@pytest.fixture", "def client():", "    from app.main import app  # adjust import", "    return TestClient(app)", ""]
        for c in cs:
            fn = re.sub(r"[^a-z0-9]+", "_", c.title.lower()).strip("_")[:50]
            lines += ["", f"@pytest.mark.{level}", f"@pytest.mark.priority('{c.priority}')", f"def test_{fn}({'client' if level == 'api' else ''}):", f'    """{c.title}', f"    Requirement: {c.requirement_ref}", f"    Expected: {c.expected}", '    """']
            for s in c.steps:
                lines.append(f"    # {s}")
            if c.destructive:
                lines.append("    pytest.skip('destructive test: requires explicit authorisation and a disposable environment')")
            else:
                lines.append("    assert False, 'implement: ' + " + repr(c.expected[:80]))
        files[f"tests/{level}/test_{mod}_{level}.py"] = "\n".join(lines) + "\n"
    return files


@register
class QATestingAgent(BaseAgent):
    spec = AgentSpec(
        key="qa_testing",
        name="QA Testing Agent",
        department="technology_product",
        version="1.0.2",
        description="Turns requirements and bug reports into structured test cases and pytest skeletons; execution is proposed only against authorised test environments, never production.",
        use_cases=["Test plan generation", "Regression test scaffolding", "API contract tests"],
        input_model=QAIn,
        output_model=QAOut,
        allowed_tools=["monitoring.test_environments", "issues.create", "platform.create_task"],
        permission_scopes=["monitoring:read", "issues:write", "tasks:write"],
        policies=["authorized_test_environments_only", "no_production_targets", "destructive_requires_authorization"],
        approval_rules=[ApprovalRule(action_type="qa.execute", condition="any test execution request")],
        timeout_seconds=90,
        token_budget=12000,
        risk_level="medium",
        baseline_minutes_saved=45,
    )

    def run(self, ctx: AgentContext, payload: QAIn, services: AgentServices) -> AgentResult:  # type: ignore[override]
        result = AgentResult(status="completed")
        wrapped = guard_untrusted(result, payload.requirements, "requirements")
        reqs = [s for s in sentences(payload.requirements) if len(s) > 12][:25]
        for i, r in enumerate(reqs, start=1):
            result.add_evidence(f"requirement:{i}", excerpt=r[:160], source_type="input")
        cases = services.structured(
            task="qa_test_cases", schema=CaseSet,
            system="Produce structured test cases (unit/integration/api/e2e) for each requirement sentence, referencing requirement:<n>. Include negative cases. Mark destructive=true for any test that deletes data, loads/stresses systems or alters infrastructure.",
            user=f"Title: {payload.title}\nKind: {payload.kind}\n{wrapped}", heuristic=lambda: heuristic_cases(payload, reqs),
        ).cases
        valid_refs = {f"requirement:{i}" for i in range(1, len(reqs) + 1)}
        cases = [c for c in cases if c.requirement_ref in valid_refs]
        for c in cases:
            if any(d in (" ".join(c.steps) + c.title).lower() for d in DESTRUCTIVE):
                c.destructive = True
        envs = services.tools.call("monitoring.test_environments").get("items", [])
        env_names = {e["name"]: e for e in envs}
        env_info: dict[str, Any] = {"requested": payload.target_environment, "authorized": False, "available": list(env_names)}
        execution: dict[str, Any] = {"status": "not_requested"}
        if payload.target_environment:
            tgt = payload.target_environment
            if any(w in tgt.lower() for w in PROD_WORDS) or env_names.get(tgt, {}).get("tier") == "production":
                env_info["authorized"] = False
                execution = {"status": "refused", "reason": "Production targets are never used for test execution"}
                result.warnings.append("Refused: test execution against a production environment")
            elif tgt in env_names and env_names[tgt].get("authorized_for_tests", True):
                env_info["authorized"] = True
                result.add_evidence(f"monitoring:test_environment:{tgt}", excerpt=str(env_names[tgt].get("tier")), source_type="monitoring")
            else:
                execution = {"status": "refused", "reason": f"'{tgt}' is not an authorised test environment"}
        destructive = sum(1 for c in cases if c.destructive)
        if payload.request_execution and env_info["authorized"]:
            execution = {"status": "proposed_pending_approval", "environment": payload.target_environment, "cases": len(cases), "destructive_excluded": destructive}
            result.proposed_actions.append(ProposedAction(action_type="qa.execute", tool_key="issues.create", payload={"project": ctx.agent_config.get("qa_project", "ENG"), "title": f"Execute test plan: {payload.title} on {payload.target_environment}", "description": f"{len(cases)} case(s); destructive cases excluded: {destructive}. Approve to schedule the run in CI.", "priority": "medium", "issue_type": "task", "labels": ["qa", "test-run"]}, reason="Test execution requires authorisation", risk_level="medium", requires_approval=True, evidence_refs=[f"monitoring:test_environment:{payload.target_environment}"], estimated_minutes_saved=20))
        elif payload.request_execution and not env_info["authorized"]:
            result.missing_information.append("An authorised, non-production test environment")
        code = render_pytest(payload, cases)
        result.proposed_actions.append(ProposedAction(action_type="platform.create_task", tool_key="platform.create_task", payload={"title": f"Review generated test plan: {payload.title}", "description": f"{len(cases)} test case(s) across {sorted({c.level for c in cases})}; {destructive} destructive case(s) flagged.", "priority": "medium", "labels": ["qa"], "evidence_refs": result.evidence_refs[:5]}, reason="Human review of generated tests", risk_level="low"))
        notes = [f"{len(reqs)} requirement sentence(s) parsed", f"{len(cases)} case(s): " + ", ".join(f"{lvl} {sum(1 for c in cases if c.level == lvl)}" for lvl in ("unit", "integration", "api", "e2e") if any(c.level == lvl for c in cases))]
        uncovered = valid_refs - {c.requirement_ref for c in cases}
        if uncovered:
            notes.append(f"Uncovered requirements: {', '.join(sorted(uncovered))}")
        result.data = QAOut(title=payload.title, test_cases=cases, generated_code=code, environment=env_info, execution=execution, destructive_cases=destructive, coverage_notes=notes).model_dump()
        result.summary = f"{len(cases)} test case(s) generated for '{payload.title}' ({destructive} destructive flagged); execution {execution['status']}"
        result.confidence = 0.8 if cases else 0.3
        result.estimated_minutes_saved = self.spec.baseline_minutes_saved
        return result
